"""把真实TestClient响应生成为TS赋值检查，防止手写契约与Python接口静默分叉。"""
import argparse
from contextlib import ExitStack
import json
import os
from pathlib import Path
import sys
import tempfile
from unittest.mock import patch

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))


def literal(value):
    if isinstance(value, dict):
        return '{'+','.join(json.dumps(k, ensure_ascii=False)+':'+literal(v) for k,v in value.items())+'}'
    if isinstance(value, list):
        return '['+','.join(literal(v) for v in value)+']'
    text = json.dumps(value, ensure_ascii=False, allow_nan=False)
    return text+' as const' if isinstance(value, (str, int, float)) else text


def export(output):
    # 所有写入与API会话绑定均位于临时目录，不触碰用户已保存项目。
    with tempfile.TemporaryDirectory(prefix='wq-contracts-') as work, ExitStack() as stack:
        stack.enter_context(patch.dict(os.environ, {'WQ_PROJECT_HOME':work}))
        previous = Path.cwd()
        stack.callback(os.chdir, previous)
        os.chdir(work)  # 模型图片等运行产物也放临时目录。
        from fastapi.testclient import TestClient
        from backend.main import app
        from backend.session import STORE
        from backend.agent.progress import AgentRun
        import pandas as pd
        client = stack.enter_context(TestClient(app))
        sid = client.get('/api/session').json()['session_id']
        stack.callback(STORE.drop, sid)
        headers = {'X-Session-Id':sid}
        cases = []

        def response(typ, path, body=None):
            res = client.get(path, headers=headers) if body is None else client.post(path, headers=headers, json=body)
            res.raise_for_status()
            cases.append((typ,res.json()))
            return res.json()

        response('Config','/api/config')
        response('DataStatus','/api/data/status')
        response('ProjectState','/api/projects')
        response('AgentRun','/api/agent/run')
        session = STORE.get(sid)
        session.df = pd.DataFrame({'datetime':pd.date_range('2025-01-01',periods=6,freq='10s'),
                                  'ammonia_nitrogen':[.2]*6,'dissolved_oxygen':[7.,0.,7.,7.,7.,7.]})
        session.data_filename = 'CI_仿真_非实测.csv'
        response('BlackSpots','/api/analysis/black-spots',{})
        response('DataStatus','/api/data/status')
        response('Preview','/api/data/preview')
        response('AnalysisResults','/api/analysis/results')
        session.messages = [{'role':'assistant','content':'CI仿真，DO最低为0。'},
                            {'role':'error','content':'受控失败历史，不代表真实服务故障。'}]
        response('ChatHistory','/api/agent/history')
        response('JsonObject','/api/river/init',{'n_cross_sections':3,'auto_detect':False})
        response('JsonObject','/api/river/hydro',{'duration_h':.5,'upstream_flow_m3s':3.})
        response('JsonObject','/api/river/pollution',{'simulation_hours':.5,'source_start_h':0.,'duration_min':5.,'load_kg':0.,'wq_refinement':2})
        response('ProjectState','/api/projects',{'name':'CI仿真契约项目','from_current':True})
        run = AgentRun(session.analysis_revision)
        session.agent_run = run
        response('AgentRun','/api/agent/run')
        run.end('partial')
        response('AgentRun','/api/agent/run')
        chunks = ["// Generated by scripts/export_frontend_contracts.py; synthetic, no remote calls.",
                  "import type * as API from '../../src/types/contracts'"]
        for index,(typ,value) in enumerate(cases):
            chunks.extend([f'const raw{index} = {literal(value)}',f'const checked{index}: API.{typ} = raw{index}',f'void checked{index}'])
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text('\n'.join(chunks)+'\n', encoding='utf-8')
        print(f'Generated {len(cases)} real backend response assignments: {output}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', type=Path, default=ROOT/'frontend/tests/types/generated_backend.contract.ts')
    export(parser.parse_args().output)
